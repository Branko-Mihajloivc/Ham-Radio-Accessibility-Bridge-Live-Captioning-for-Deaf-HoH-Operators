class WordStabilizer:
    """Turns a stream of (revisable) full-hypothesis partials + finals into
    a word-by-word ticker: each call gives back (confirmed_words, live_tail)
    where confirmed_words only ever grows and is never rewritten, and
    live_tail is the still-uncertain last word(s) of whatever is currently
    being decoded.

    Why: streaming ASR (Vosk) and periodic-redecode ASR (our Whisper
    partials) both revise their hypothesis for the CURRENT utterance as more
    audio arrives, so naively displaying "the latest partial" makes text
    visibly flicker/rewrite itself, and utterance-level batching means
    nothing shows up until a whole phrase finishes. Phrase boundaries don't
    matter for ham radio traffic (callsigns, Q-codes, single words) -- what
    matters is showing each word as soon as it's very unlikely to change,
    which in practice is as soon as a newer word appears after it.
    """

    def __init__(self):
        self.confirmed_words = []
        self._local_stable_count = 0  # words of the CURRENT utterance already folded into confirmed_words

    def on_partial(self, text):
        words = text.split()
        stable_upto = max(self._local_stable_count, len(words) - 1)  # keep the last word live
        self.confirmed_words.extend(words[self._local_stable_count:stable_upto])
        self._local_stable_count = stable_upto
        return self.confirmed_words, words[self._local_stable_count:]

    def on_final(self, text):
        words = text.split()
        self.confirmed_words.extend(words[self._local_stable_count:])
        self._local_stable_count = 0
        # Mark where this transmission ended so the continuous word ticker
        # doesn't read as one unbroken stream -- word-by-word within a
        # transmission is the point, but losing all sense of "this was one
        # transmission, that was another" makes it unreadable.
        self.confirmed_words.append(f"\n----- {time.strftime('%H:%M:%S')} -----\n")
        return self.confirmed_words, []


