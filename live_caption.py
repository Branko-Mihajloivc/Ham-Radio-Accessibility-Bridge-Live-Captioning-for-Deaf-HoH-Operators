def find_monitor_output_device():
    """Picks a playback device for the audio monitor that is NOT the
    loopback-captured device -- playing monitor audio to the same device
    being captured from (e.g. "System Default" == the Fast Track Pro on
    this machine) creates a real feedback loop (our own playback gets
    re-captured and re-played, regenerating), and even without feedback it
    overlaps/mixes with the live radio audio on the same physical speakers,
    making it useless for judging filtering by ear. Prefers a headset,
    falls back to sounddevice's default output device with a warning.
    """
    wasapi_idx = next((i for i, a in enumerate(sd.query_hostapis()) if "WASAPI" in a["name"]), None)
    for i, d in enumerate(sd.query_devices()):
        if d["max_output_channels"] > 0 and "blackwire" in d["name"].lower() and d["hostapi"] == wasapi_idx:
            return i
    print(
        "[monitor] No headset found by name -- falling back to the default output device. "
        "If that's the same device being loopback-captured, monitor audio will feedback/overlap; "
        "pass --monitor-device N (see --list-devices) to pick a safe one.",
        file=sys.stderr,
    )
    return None


class DroppingQueue:
    """A queue.Queue-like buffer for MONITORING/VISUALIZATION consumers only
    -- never for anything that feeds a recognizer (Vosk/Whisper/Deepgram
    must keep using a real queue.Queue(), since dropping audio there would
    directly hurt recognition, not just cosmetic lag).

    .put() never blocks and never grows past maxsize: once full, it
    discards the OLDEST buffered chunk to make room for the newest one,
    instead of piling up. This fixes a real bug found via live testing:
    the waterfall and audio monitor share one raw-audio tap fed by a plain
    unbounded queue.Queue(), and two independently-clocked audio devices
    (capture vs. playback) essentially never run at EXACTLY the same rate
    -- even a tiny, persistent mismatch means the consumer falls a little
    further behind every single chunk, with no ceiling. Confirmed live:
    the waterfall was updating one line every 2-3 seconds instead of the
    expected ~21ms, and separately the audio monitor's playback of the
    user's own voice drifted up to ~10 seconds behind real-time the longer
    a session ran -- both symptoms of the exact same unbounded backlog,
    not two different bugs. Bounding it here caps worst-case monitoring
    lag at roughly maxsize chunks' worth of audio, trading "keep every
    sample" (irrelevant for a live visual/listening aid) for "never fall
    further behind than a fixed ceiling" (the actual requirement).
    """

    def __init__(self, maxsize):
        self._q = queue.Queue(maxsize=maxsize)

    def put(self, item):
        while True:
            try:
                self._q.put_nowait(item)
                return
            except queue.Full:
                try:
                    self._q.get_nowait()
                except queue.Empty:
                    pass

    def get(self, *args, **kwargs):
        return self._q.get(*args, **kwargs)

    def empty(self):
        return self._q.empty()

    def qsize(self):
        return self._q.qsize()


def start_audio_monitor(raw_monitor_q, processed_monitor_q, mode_cell, waterfall_buffer, stop_event, monitor_device=None,
                         pitch_track=None, latest_pitch=None, latest_snr=None, latest_latency=None):
    """Two background threads:
      - drains raw_monitor_q (48kHz pre-filter audio): always updates
        waterfall_buffer (a shared 2D numpy array the GUI redraws from), and
        plays it back through the shared output stream when mode_cell[0]
        == "raw".
      - drains processed_monitor_q (16kHz post-filter audio): plays it back
        (upsampled to 48kHz) when mode_cell[0] == "processed".
    Both queues are always drained regardless of mode, so switching modes
    or leaving it off never lets a queue back up unbounded. mode_cell is a
    1-element list so the GUI can flip it live without any lock (mode
    strings are read/written atomically enough for this purpose).

    monitor_device routes playback away from whatever's being loopback-
    captured -- see find_monitor_output_device().
    """
    if monitor_device is None:
        monitor_device = find_monitor_output_device()
    if monitor_device is not None:
        print(f"[monitor] Playing back to device {monitor_device}: {sd.query_devices(monitor_device)['name']}")
    # channels=2: the headset only advertises stereo output
    # (max_output_channels=2) -- requesting mono from a WASAPI device that
    # doesn't cleanly support it can cause a channel-count mismatch where
    # samples get reinterpreted (a classic cause of exactly this kind of
    # pitch/garbling artifact). Duplicate mono to both channels instead of
    # relying on the device to handle channels=1 correctly.
    # latency="high" gives PortAudio a bigger internal buffer against CPU
    # contention from the other engines.
    out_stream = sd.OutputStream(samplerate=LOOPBACK_RATE, channels=2, dtype="int16", device=monitor_device, latency="high")
    out_stream.start()
    freq_bin_limit = int(WATERFALL_FFT_SIZE * WATERFALL_MAX_HZ / LOOPBACK_RATE)
    window = np.hanning(WATERFALL_FFT_SIZE)

    def to_stereo(mono_samples):
        return np.column_stack((mono_samples, mono_samples))

    # PER-BIN noise-floor tracking with a fixed dynamic-range ceiling.
    # Two earlier attempts both used a single SCALAR floor/ceiling for the
    # whole spectrum, and both failed for the same underlying reason: voice/
    # radio audio isn't spectrally flat -- low frequencies (roughly below
    # ~1.5kHz) naturally carry far more energy than higher ones. A global
    # floor+ceiling judges every bin against the same reference, so the
    # naturally-louder low bins sit permanently pegged at the ceiling
    # (solid white) REGARDLESS of whether anyone is transmitting, burying
    # the actual signal-vs-noise variation that only shows up as a small
    # relative change on top of that. Confirmed directly: three real test
    # screenshots at very different S-meter readings (S7 noise floor, S9+10,
    # S7 signal) all looked visually identical -- solid white on the same
    # ~half of the frequency range every time.
    # Fix: track a separate floor value PER FREQUENCY BIN, so each bin is
    # judged against its own typical quiet level, not the whole spectrum's.
    # Uses an asymmetric tracker per bin (classic "minimum statistics" noise
    # estimation): fall quickly toward a quiet bin (find the true floor
    # fast), rise slowly when a bin gets louder (so a real transmission
    # doesn't get absorbed into "new normal" within a second or two, which
    # would erase it again). A weak rise above a bin's own floor now shows
    # real color contrast immediately, regardless of which frequency it's
    # at or how loud neighboring bins naturally run.
    bin_floor = np.full(freq_bin_limit, WATERFALL_DB_FLOOR, dtype=np.float64)
    FLOOR_FALL_RATE = 0.2   # quiet bins: floor drops toward them fast
    FLOOR_RISE_RATE = 0.01  # loud bins: floor creeps up slowly

    # Live SNR/RMS estimate -- same asymmetric-tracker idea as the per-bin
    # floor above, but a single SCALAR on the overall frame RMS (dBFS),
    # since that's the same unit the level meter/dBFS readout already uses
    # elsewhere, making it directly comparable rather than mixing dB
    # references. SNR = current level minus the tracked floor.
    # Numbers are additionally low-pass smoothed before display (SNR_ALPHA)
    # -- raw per-frame values update ~93x/sec, far too fast for a human to
    # read as a stable number; per the explicit request that "numbers moving
    # fast can make trouble," the DISPLAYED figure is deliberately smoothed
    # separately from the floor tracker's own (differently-paced) smoothing.
    # ALPHA=0.08 (settles in ~130ms) was confirmed via live testing to still
    # be too jittery to read reliably -- 0.01 gives roughly a 1-second
    # settling time, closer to "a calm number you can actually read" while
    # still responding fast enough to reflect a transmission starting/ending.
    noise_floor_db = [-60.0]
    smoothed_rms_db = [-60.0]
    smoothed_snr_db = [0.0]
    SNR_FLOOR_FALL_RATE = 0.05
    SNR_FLOOR_RISE_RATE = 0.005
    SNR_DISPLAY_ALPHA = 0.01

    def raw_worker():
        nonlocal bin_floor
        while not stop_event.is_set():
            try:
                chunk_bytes = raw_monitor_q.get(timeout=0.2)
            except queue.Empty:
                continue
            samples = np.frombuffer(chunk_bytes, dtype=np.int16)
            if len(samples) and latest_latency is not None:
                # Approximation, not a precise end-to-end measurement: how
                # much audio is CURRENTLY sitting in this queue waiting to
                # be played, i.e. buffering delay. Doesn't capture the
                # audio output device's own internal latency or (in
                # Processed mode) upstream processing-stage latency, but
                # captures the dominant, most variable source -- how far
                # behind real-time this specific queue has fallen -- with
                # no new plumbing (reuses DroppingQueue's own qsize()).
                chunk_ms = len(samples) / LOOPBACK_RATE * 1000
                latest_latency[0] = raw_monitor_q.qsize() * chunk_ms
            if len(samples):
                frame_db = 20 * np.log10(max(rms(samples), 1.0) / 32768.0)
                if frame_db < noise_floor_db[0]:
                    noise_floor_db[0] += (frame_db - noise_floor_db[0]) * SNR_FLOOR_FALL_RATE
                else:
                    noise_floor_db[0] += (frame_db - noise_floor_db[0]) * SNR_FLOOR_RISE_RATE
                snr_db = frame_db - noise_floor_db[0]
                smoothed_rms_db[0] += (frame_db - smoothed_rms_db[0]) * SNR_DISPLAY_ALPHA
                smoothed_snr_db[0] += (snr_db - smoothed_snr_db[0]) * SNR_DISPLAY_ALPHA
                if latest_snr is not None:
                    latest_snr[0] = (smoothed_rms_db[0], noise_floor_db[0], smoothed_snr_db[0])
            if len(samples) >= WATERFALL_FFT_SIZE:
                windowed = samples[:WATERFALL_FFT_SIZE].astype(np.float64) * window
                mag = np.abs(np.fft.rfft(windowed))[:freq_bin_limit]
                db = 20 * np.log10(mag + 1.0)
                if db.size:
                    rate = np.where(db < bin_floor, FLOOR_FALL_RATE, FLOOR_RISE_RATE)
                    bin_floor = bin_floor + (db - bin_floor) * rate
                col = np.clip((db - bin_floor) / WATERFALL_DYNAMIC_RANGE_DB, 0, 1) if db.size else db
                waterfall_buffer[:, :-1] = waterfall_buffer[:, 1:]
                # Not reversed: low frequency at index 0 -- normal left-to-right
                # spectrum order once this becomes the image's horizontal axis.
                waterfall_buffer[:, -1] = np.interp(
                    np.linspace(0, len(col) - 1, WATERFALL_HEIGHT_PX), np.arange(len(col)), col
                ) if len(col) else 0
                if pitch_track is not None:
                    result = estimate_pitch(samples[:WATERFALL_FFT_SIZE], LOOPBACK_RATE)
                    pitch_track[:-1] = pitch_track[1:]
                    if result is not None:
                        f0, confidence = result
                        pitch_track[-1] = f0
                        if latest_pitch is not None:
                            latest_pitch[0] = (f0, confidence)
                    else:
                        pitch_track[-1] = np.nan
                        if latest_pitch is not None:
                            latest_pitch[0] = None
            if mode_cell[0] == "raw":
                try:
                    out_stream.write(to_stereo(samples))
                except Exception as e:
                    print(f"[monitor] raw playback write failed: {e}", file=sys.stderr)

    resample_state = [None]

    def processed_worker():
        while not stop_event.is_set():
            try:
                chunk_bytes = processed_monitor_q.get(timeout=0.2)
            except queue.Empty:
                continue
            if mode_cell[0] == "processed":
                up, resample_state[0] = audioop.ratecv(
                    chunk_bytes, 2, 1, TARGET_RATE, LOOPBACK_RATE, resample_state[0]
                )
                try:
                    out_stream.write(to_stereo(np.frombuffer(up, dtype=np.int16)))
                except Exception as e:
                    print(f"[monitor] processed playback write failed: {e}", file=sys.stderr)

    threading.Thread(target=raw_worker, daemon=True).start()
    threading.Thread(target=processed_worker, daemon=True).start()


