# Per-bin spectral gate: the "aggressive audio conditioning" stage, built on
# the same per-bin noise-floor tracker just validated on the waterfall (see
# start_audio_monitor) -- fall fast toward quiet bins, rise slowly on loud
# ones, so each frequency bin is judged against its OWN typical background
# rather than one global level. Unlike the earlier bandpass/NLMS attempts
# (both proved harmful by A/B test), this only touches bins currently
# reading near their own floor, wherever in the spectrum that is, rather
# than blanket-filtering or assuming a fixed noise model up front.
# Disabled by default -- toggle live via the GUI checkbox to A/B it, per the
# established lesson: trust a real transcription comparison, not DSP theory.
SPECTRAL_GATE_ENABLED = False
SPECTRAL_GATE_FFT_SIZE = 4096  # ~85ms at 48kHz -- see harmonic-protection comment below for why this isn't 1024 anymore
SPECTRAL_GATE_HOP = 2048  # 50% overlap
SPECTRAL_GATE_ATTEN_DB = 15.0  # how hard to push down below-floor bins
SPECTRAL_GATE_MARGIN_DB = 6.0  # soft-knee width around the floor -- avoids hard on/off "musical noise" zipper artifacts
SPECTRAL_GATE_FLOOR_FALL_RATE = 0.2
SPECTRAL_GATE_FLOOR_RISE_RATE = 0.01
# Harmonic-aware protection: confirmed via live A/B testing (2026-09-08)
# that the plain per-bin floor-relative gate above made no measurable
# difference to recognition accuracy at any tested SNR -- it can't tell
# voice-shaped energy from noise-shaped energy, only loud from quiet. This
# adds real structure: each frame also runs the same pitch estimator
# already validated on the waterfall: if a fundamental (F0) is detected,
# bins that land on one of ITS harmonics (F0, 2xF0, 3xF0, ...) are trusted
# as real voice and protected from attenuation regardless of the floor-
# relative check. Bins that don't land near a harmonic are gated exactly
# as before. When no pitch is detected at all (silence, or genuinely
# unvoiced consonants like s/f/sh/th, which have no harmonic structure by
# nature), this falls back to the plain floor-relative behavior -- so
# fricatives aren't penalized just for lacking a pitch to protect them.
# The real payoff: because confirmed-harmonic content is now explicitly
# shielded, the attenuation depth can be pushed much harder on everything
# else without the same risk of chewing up real voice that made a high
# atten_db unsafe with the plain version.
SPECTRAL_GATE_HARMONIC_TOLERANCE_HZ = 40.0  # width of the protection window around each harmonic
SPECTRAL_GATE_HARMONIC_MAX_HZ = 4000.0  # don't bother protecting harmonics above typical SSB voice content
SPECTRAL_GATE_PITCH_HOLD_FRAMES = 4  # ~170ms at the current hop size -- bridges brief real-speech pitch dropouts
# Offline A/B testing (comparing gate-on vs gate-off at the same analysis
# frequency, not just eyeballing a spectrum) caught a real problem with the
# original FFT_SIZE=1024 (~47Hz/bin): for a typical male voice around
# 120Hz, harmonics are only ~2.5 bins apart -- far too coarse for the mask
# to distinguish "on a harmonic" from "between harmonics." The mask ended
# up varying too sharply relative to what a 1024-point FFT can resolve,
# and reconstructing audio from a mask that jagged introduced its own
# smearing/leakage -- the between-harmonic content measured LOUDER with
# the gate on than off, the opposite of the intended effect. FFT_SIZE=4096
# (~11.7Hz/bin) gives enough resolution to properly separate harmonics even
# for low-pitched voices, at the cost of real added latency (~85ms/frame
# vs ~21ms) -- a genuine trade-off for a live captioning tool, accepted
# here because a gate that doesn't work isn't worth having at any latency.

# Noise Blanker -- targets a DIFFERENT noise category than the gate above:
# impulse noise (ignition noise, switching clicks) rather than steady hiss.
# User's own real-noise recording was specifically characterized as
# "crackles and pops... not the actual hiss," which is exactly impulse
# noise's signature -- broadband but extremely brief (microseconds to a
# couple ms), unlike continuous band noise. Modeled on how a real radio's
# hardware noise blanker works: operates in the TIME domain (no FFT at
# all), watching instantaneous amplitude against a slow-moving baseline of
# what's "normal" -- when a sample spikes far above that baseline, faster
# than real voice could ever rise, blank (mute) just that brief instant and
# resume immediately. Because the blanked duration is so short, it's
# inaudible as a gap, but it removes exactly the kind of noise spectral
# subtraction/gating (both frequency-domain, both too slow/coarse to
# isolate a sub-millisecond spike without smearing it across a whole
# analysis frame) can't touch cleanly. Complementary layer, not a
# replacement -- meant to run alongside spectral techniques, each handling
# the noise type it's actually suited for.
NOISE_BLANKER_ENABLED = False
NOISE_BLANKER_THRESHOLD_DB = 12.0  # how far above the tracked baseline triggers a blank
NOISE_BLANKER_BLANK_SAMPLES = 24  # ~0.5ms at 48kHz -- real impulse noise duration
NOISE_BLANKER_BASELINE_FALL_RATE = 0.05  # baseline drops toward quiet quickly
NOISE_BLANKER_BASELINE_RISE_RATE = 0.005  # rises slowly -- don't let real loud speech peaks redefine "normal"
NOISE_BLANKER_FADE_SAMPLES = 12  # width of the fade in/out around each blanked region -- avoids a hard-cut click
NOISE_BLANKER_JUMP_RATIO = 0.6  # required sample-to-sample jump, as a fraction of the level threshold -- rejects gradual (even if loud/fast) speech peaks

# Spectral subtraction -- the OTHER complementary layer, for steady/
# continuous noise the blanker can't touch (it only handles brief
# impulses). Unlike the Spectral Gate (which multiplies each bin by a
# mask, a volume knob per bin), this SUBTRACTS the tracked noise floor's
# actual magnitude from every frame, additively -- "remove exactly this
# much, every time" rather than "turn this down because it looks quiet."
# Doesn't need to identify voice at all (sidesteps the harmonic-matching
# problem that didn't pay off for the gate): whatever's left after
# removing the known noise profile IS the excess, i.e. signal above it.
# Known classical failure mode: "musical noise" -- real noise is random
# even when stationary on average, so subtracting the average doesn't
# perfectly cancel any single frame's actual instance, leaving scattered
# residual artifacts. SPECTRAL_SUBTRACTION_FLOOR (never subtract to
# absolute zero) and SPECTRAL_SUBTRACTION_OVER_SUBTRACT are the standard
# mitigations, tuned here only as reasonable starting points.
SPECTRAL_SUBTRACTION_ENABLED = False
SPECTRAL_SUBTRACTION_FFT_SIZE = 2048  # ~43ms at 48kHz -- less latency-hungry than the gate's harmonic version since this doesn't need pitch resolution, just a stable noise-floor estimate
SPECTRAL_SUBTRACTION_HOP = 1024  # 50% overlap
SPECTRAL_SUBTRACTION_OVER_SUBTRACT = 1.5  # subtract more than the raw estimate -- standard practice, reduces musical noise at the cost of removing a bit of real signal too
SPECTRAL_SUBTRACTION_FLOOR = 0.05  # never let a bin's magnitude drop below 5% of its original -- avoids the harshest musical-noise artifacts from full nulling
SPECTRAL_SUBTRACTION_FLOOR_FALL_RATE = 0.2
SPECTRAL_SUBTRACTION_FLOOR_RISE_RATE = 0.01

# Noise Gate -- broadband, time-domain squelch/expander, applied AFTER
# spectral subtraction. Different job than either spectral stage above:
# those shape the SPECTRUM within a frame; this decides, frame to frame,
# whether the frame is speech at all, and turns down whatever's left
# (residual hiss, or subtraction's own "musical noise") when it isn't --
# specifically targeting the gaps BETWEEN words/phonemes that neither the
# per-bin stages nor the coarser webrtcvad utterance-level segmentation
# touch (that segmentation only starts/stops whole utterances; it doesn't
# gate anything mid-utterance).
# Deliberately NOT a plain RMS/level threshold -- that's the exact approach
# already ruled out for this signal (see the note above VAD_FRAME_MS: "a
# plain RMS-threshold gate ... turned out to be unworkable against real
# radio noise ... a station can be fully intelligible while amplitude-
# indistinguishable from the noise floor"). Primary open signal is instead
# the same voiced-frame pitch detector already validated in Spectral
# Subtraction/Gate; a lenient loudness check is only OR'd in secondarily,
# to still pass real but unvoiced content (fricatives like s/f/sh have no
# pitch at all to detect). Never fully mutes when "closed" (see FLOOR_DB) --
# at this SNR range even unvoiced real speech can sit close to the noise
# floor, so a hard mute risks chopping it; a soft reduction hedges against
# that while still meaningfully quieting the gaps.
# Runs on its own rolling analysis window (independent of the caller's
# small hardware-callback chunk size) so the pitch estimate has enough
# samples to resolve low male F0s reliably, same reasoning as Spectral
# Subtraction's own FFT size -- but applies the result as a plain smoothed
# gain multiply (attack/release, like a compressor's envelope), not an
# FFT/OLA reconstruction, since a broadband gate doesn't need per-bin
# resolution to do its job.
