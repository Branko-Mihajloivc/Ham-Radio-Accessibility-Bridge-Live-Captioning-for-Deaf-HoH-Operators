NOISE_GATE_ANALYSIS_SAMPLES = 2048  # ~43ms at 48kHz -- long enough for reliable pitch detection down to 70Hz
NOISE_GATE_THRESHOLD_DB = 6.0  # secondary loudness check: dB above tracked floor that counts as "loud enough" on its own
NOISE_GATE_FLOOR_DB = -12.0  # gain applied while "closed" -- attenuation, not a full mute
NOISE_GATE_ATTACK_MS = 5.0  # fast open -- don't clip the start of a word
NOISE_GATE_RELEASE_MS = 150.0  # slower close -- avoid chopping trailing consonants or audible pumping
NOISE_GATE_FLOOR_TRACK_FALL_RATE = 0.05
