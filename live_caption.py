def _build_waterfall_lut():
    """Classic SDR-style waterfall palette (black -> blue -> cyan -> green ->
    yellow -> red -> white), matching the style of a real panadapter/
    waterfall rather than plain grayscale. Precomputed as a 256-entry LUT so
    applying it to a frame is one fast numpy fancy-index, not a per-pixel loop.
    """
    stops = [
        (0.00, (0, 0, 0)),
        (0.15, (0, 0, 130)),
        (0.35, (0, 160, 220)),
        (0.55, (0, 220, 80)),
        (0.75, (255, 220, 0)),
        (0.90, (255, 60, 0)),
        (1.00, (255, 255, 255)),
    ]
    xs = np.array([s[0] for s in stops])
    lut = np.zeros((256, 3), dtype=np.uint8)
    for ch in range(3):
        ys = np.array([s[1][ch] for s in stops])
        lut[:, ch] = np.interp(np.linspace(0, 1, 256), xs, ys)
    return lut


WATERFALL_LUT = _build_waterfall_lut()

# Pitch tracking overlay -- validating this against real, noisy ham audio is
# step one of a different approach: track the actual speaker's fundamental
# frequency (voice is harmonic, band hiss/static isn't) instead of a fixed
# frequency band or a generic pre-trained denoiser. Pure diagnostic for now,
# no filtering built on it yet -- prove the tracking holds up first.
PITCH_FMIN_HZ = 70   # below typical low male voice F0
PITCH_FMAX_HZ = 400  # above typical high female voice F0
PITCH_CONFIDENCE_MIN = 0.35  # autocorrelation peak strength -- below this, treat as unvoiced/noise, not a wrong pitch


def estimate_pitch(samples_int16, sample_rate):
    """Autocorrelation-based F0 estimate. Returns (f0_hz, confidence) or
    None if the segment doesn't look voiced (silence, noise, or unvoiced
    consonants -- which is a useful side effect: this only reports a pitch
    when the signal is genuinely periodic, which noise/hiss never is).
    """
    x = samples_int16.astype(np.float64)
    x -= x.mean()
    # This is a numerical guard against true digital silence (all-zero
    # samples, which would make acf[0]==0 below), NOT a "loud enough to
    # bother" gate -- the confidence score is already scale-invariant
    # (normalized by its own zero-lag value), so pitch detection works
    # the same regardless of input gain. A higher threshold here used to
    # silently break detection whenever the software input-gain slider
    # was turned down, since real signal at low gain still has a small
    # absolute amplitude even though it's perfectly analyzable.
    if np.abs(x).max() < 1e-6:
        return None
    n = len(x)
    fft_size = 1
    while fft_size < 2 * n:
        fft_size *= 2
    spectrum = np.fft.rfft(x, n=fft_size)
    acf = np.fft.irfft(spectrum * np.conj(spectrum))[:n]
    if acf[0] <= 0:
        return None
    acf /= acf[0]
    min_lag = int(sample_rate / PITCH_FMAX_HZ)
    max_lag = min(int(sample_rate / PITCH_FMIN_HZ), n - 1)
    if min_lag >= max_lag:
        return None
    segment = acf[min_lag:max_lag]
    if len(segment) < 3:
        return None
    peak_idx = int(np.argmax(segment))
    # Reject peaks sitting exactly on the search-range edge -- validated
    # against real radio audio, and a real chunk of the "detections" were
    # landing precisely on PITCH_FMAX_HZ's boundary, which is what happens
    # when the true peak lies outside the search window (or it's noise, not
    # a genuine periodic signal) rather than a real interior local maximum.
    if peak_idx == 0 or peak_idx == len(segment) - 1:
        return None
    confidence = float(segment[peak_idx])
    if confidence < PITCH_CONFIDENCE_MIN:
        return None
    lag = min_lag + peak_idx
    return sample_rate / lag, confidence

