    make_slider(3, 1, "NB threshold dB", 4, 30, filter_params["noise_blanker_threshold_db"], "noise_blanker_threshold_db", resolution=1)
    make_slider(3, 3, "Blank ms", 0.2, 3.0, filter_params["noise_blanker_blank_ms"], "noise_blanker_blank_ms", resolution=0.1)

    spectral_subtraction_enabled_var = tk.BooleanVar(value=filter_params["spectral_subtraction_enabled"])

